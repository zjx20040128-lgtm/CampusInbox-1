const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const assert = require('assert');
const root = path.resolve(__dirname, '..');
const os=require('os');
const {spawn}=require('child_process');
let url=process.env.CI_TEST_URL, managedServer, temporaryDirectory, testBrowser;
async function startTestServer(){
  if(url)return;
  temporaryDirectory=fs.mkdtempSync(path.join(os.tmpdir(),'courseinbox-test-'));
  const bundled=path.join(os.homedir(),'.cache','codex-runtimes','codex-primary-runtime','dependencies','python','python.exe');
  const python=process.env.CI_PYTHON || (fs.existsSync(bundled)?bundled:'python');
  managedServer=spawn(python,[path.join(root,'server.py'),'--port','0','--data-dir',temporaryDirectory],{cwd:root,windowsHide:true});
  url=await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error('test server startup timed out')),15000);
    managedServer.stdout.on('data',chunk=>{const match=chunk.toString().match(/ready: (http:\/\/127\.0\.0\.1:\d+)/);if(match){clearTimeout(timer);resolve(match[1])}});
    managedServer.on('error',e=>{clearTimeout(timer);reject(e)});
    managedServer.stderr.on('data',chunk=>process.stderr.write(chunk));
    managedServer.on('exit',code=>{if(!url){clearTimeout(timer);reject(new Error('test server exited '+code))}});
  });
}
(async () => {
  await startTestServer();
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  testBrowser=browser;
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('response',r=>{if(r.status()>=400)console.log('HTTP failure',new URL(r.url()).pathname,r.status())});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url);
  await page.getByRole('heading',{name:'把通知，变成清晰的下一步。'}).waitFor();
  await page.getByRole('button',{name:'加载示例数据',exact:true}).first().click();
  await page.getByText('软件工程',{exact:true}).first().waitFor();
  await page.locator('.sidebar [data-view="inbox"]').click();
  const extension=page.locator('.proposal-card').filter({hasText:'延期'}).first();
  await extension.getByRole('button',{name:'确认变更',exact:true}).click();
  await page.getByText('变更已确认',{exact:true}).waitFor();
  await page.locator('#importOpen').click();
  await page.locator('#noticeText').fill('《浏览器测试课程》 第一次作业：请提交实验报告、源代码。截止：2026年10月20日 18:30。');
  await page.locator('#noticeScope').fill('浏览器验收班');
  await page.locator('#importSubmit').click();
  const custom=page.locator('.proposal-card').filter({hasText:'浏览器测试课程'});
  await custom.getByRole('button',{name:'确认创建'}).click();
  await page.locator('.sidebar [data-view="tasks"]').click();
  await page.locator('#taskSearch').fill('浏览器测试课程');
  await page.locator('.task-row').filter({hasText:'浏览器测试课程'}).getByRole('button',{name:'查看详情'}).click();
  await page.locator('#taskDialog').getByLabel('实验报告',{exact:true}).check();
  await page.locator('#detailStatus').selectOption('done');
  await page.getByText('已做完，记得在原平台提交',{exact:true}).waitFor();
  await page.locator('#detailStatus').selectOption('submitted');
  await page.locator('#taskDialog [data-close]').click();
  await page.locator('.sidebar [data-view="calendar"]').click();
  const downloadEvent=page.waitForEvent('download');
  await page.locator('#exportCalendar').click();
  const download=await downloadEvent;
  const file=await download.path();
  const calendar=fs.readFileSync(file,'utf8');
  assert(calendar.includes('BEGIN:VEVENT'));
  assert(calendar.includes('20261020T103000Z'));
  await page.locator('#importOpen').click();
  await page.locator('#noticeFile').setInputFiles(path.join(root,'samples','sample-notice.png'));
  await page.getByText(/Windows 中文 OCR/).waitFor({timeout:45000});
  assert((await page.locator('#noticeText').inputValue()).includes('第三次作业'));
  await page.locator('#importDialog [data-close]').first().click();
  await page.locator('#assistantOpen').click();
  await page.locator('#assistantQuestion').fill('我还有哪些作业没提交？');
  await page.locator('#assistantSubmit').click();
  await page.locator('#assistantAnswer').getByText(/尚未提交/).waitFor();
  await page.locator('#assistantDialog [data-close]').click();
  await page.locator('.sidebar [data-view="mobile"]').click();
  await page.getByRole('heading',{name:'让手机通知进入收件箱'}).waitFor();
  await page.locator('#tokenReveal').click();
  const token=await page.locator('#pairToken').inputValue();
  assert(token.length>24);
  const response=await page.request.post(url+'/api/mobile/notifications',{headers:{Authorization:'Bearer '+token},data:{package_name:'com.chaoxing.mobile',notification_key:'browser-test:'+Date.now(),title:'《手机验收》 实验1',text:'明天18:00前提交实验报告。',captured_at:new Date().toISOString(),scope:'手机验收班'}});
  assert.strictEqual(response.status(),201);
  await page.locator('#refreshButton').click();
  await page.locator('.sidebar [data-view="inbox"]').click();
  await page.getByText('Android · com.chaoxing.mobile',{exact:false}).first().waitFor();
  await page.locator('.sidebar [data-view="today"]').click();
  fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
  await page.screenshot({path:path.join(root,'artifacts','desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(root,'artifacts','mobile.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth), 'mobile overflow');
  assert.deepStrictEqual(errors,[]);
  const result={passed:true,journeys:['demo','extension review','text import','confirmation','checklist','done/submitted','calendar download','real screenshot OCR','offline assistant','Android ingest','mobile viewport'],browser:'Edge',consoleErrors:errors};
  fs.writeFileSync(path.join(root,'docs','verification','browser-result.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{
  if(testBrowser)await testBrowser.close();
  if(managedServer){
    const finished=new Promise(resolve=>managedServer.once('exit',resolve));
    managedServer.kill();await finished;
    const expected=path.resolve(os.tmpdir())+path.sep;
    const resolved=path.resolve(temporaryDirectory);
    if(resolved.startsWith(expected)&&path.basename(resolved).startsWith('courseinbox-test-'))fs.rmSync(resolved,{recursive:true,force:true});
  }
});
